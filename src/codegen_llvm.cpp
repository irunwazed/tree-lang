// AST bertipe → LLVM IR tekstual (.ll).
//
// Semua variabel lokal memakai alloca di blok entry; clang -O2 (mem2reg/SROA)
// mengubahnya menjadi register SSA. Karena sema sudah membuktikan semua operasi
// aman, kode release tidak berisi pengecekan runtime. Dengan debug_asserts,
// setiap bukti diverifikasi ulang saat runtime (jaring pengaman bug compiler).

